def literal_exception(literal, role):
    return role == USAGE and literal in LITERAL_EXCEPTIONS


def italic_contract(command, literal, role):
    return command == 'textit' and literal == ITALIC_LITERAL and role == ITALIC_USAGE


def qualified_usage(source, stream, index, kind):
    """Keep existing 2-isomorphism/2-category terminology semantics intact."""
    if kind not in QUALIFIED_LITERALS or not 0 < index < len(stream)-1:
        return None
    for frame in NATURAL_FRAMES:
        expected = _frame_nodes(frame)
        if not _matches(source, stream, frame, natural=True):
            continue
        target, node = expected[index], stream[index]
        if (target.get('command') != 'text'
                or target['value'] not in QUALIFIED_LITERALS[kind]
                or stream[index-1]['token'] != '2'
                or stream[index-1]['end'] != node['start']):
            continue
        return {'before': source[stream[index-1]['start']:node['start']],
                'after': source[node['end']:stream[index+1]['end']],
                'environments': node['environments']}
    return None


def _italic_matches(source, stream, frame):
    """Only plain parameter values vary; every other byte remains exact."""
    from .math_text import plain_text
    expected = _frame_nodes(frame)
    if len(stream) != len(expected):
        return False
    previous = boundary = 0
    for actual, target in zip(stream, expected):
        if (actual['depth'] != target['depth']
                or actual['environments'] != target['environments']
                or source[previous:actual['start']] != frame[boundary:target['start']]):
            return False
        if target.get('command') == 'textit' and target['value'] == ITALIC_LITERAL:
            if (actual.get('command') != 'textit' or not plain_text(actual['value'])
                    or source[actual['start']:actual['parameter_start']]
                    != frame[target['start']:target['parameter_start']]
                    or source[actual['parameter_end']:actual['end']]
                    != frame[target['parameter_end']:target['end']]):
                return False
        elif actual['token'] != target['token']:
            return False
        previous, boundary = actual['end'], target['end']
    return source[previous:] == frame[boundary:]


def usage(source, stream, index, kind):
    if kind not in USAGES or not 0 < index < len(stream) - 1:
        return None
    from .math_text import usage as ordinary_usage
    frames = ITALIC_FRAMES if kind == ITALIC_USAGE else NATURAL_FRAMES
    for frame in frames:
        expected = _frame_nodes(frame)
        if not (_italic_matches(source, stream, frame) if kind == ITALIC_USAGE
                else _matches(source, stream, frame, natural=True)):
            continue
        target = expected[index]
        if kind == ITALIC_USAGE:
            if target.get('command') != 'textit' or target['value'] != ITALIC_LITERAL:
                continue
        else:
            if target.get('command') != 'text':
                continue
            # The existing ordinary role stays authoritative where it works.
            if any(ordinary_usage(source, stream, index, role) is not None
                   for role, literal in CONTEXTS[USAGE] if literal == target['value']):
                continue
        node = stream[index]
        return {'before': source[stream[index-1]['start']:node['start']],
                'after': source[node['end']:stream[index+1]['end']],
                'environments': node['environments']}
    return None


def notation_context(source, stream, index, value, kind):
    frames = (SPACES_FRAMES if kind == 'spaces-category' and value == 'Spaces'
              else CQC_FRAMES if kind == CQC_USAGE and value == 'CQC' else ())
    if (source not in frames or not 0 <= index < len(stream)
            or stream[index].get('command') != 'textit'
            or stream[index].get('value') != value):
        return None
    return source[:stream[index]['start']] + source[stream[index]['end']:]
